def guard_positive_amount_category(amount: int, category: str | None) -> str | None:
    """Не дає додатній сумі отримати категорію витрат в автоматичних шляхах.

    Використовується правилами (MCC, ключові слова), ML і категоріями банку.
    Ручні шляхи використовують validate_manual_category_sign.

    Args:
        amount: Сума в копійках.
        category: Запропонована категорія.

    Returns:
        "pending" для додатної суми з категорією витрат; інакше category без змін
        (дохід, перекази, службові категорії, None, нуль і від'ємні суми).
    """
    if category is None or amount <= 0:
        return category
    if category in INCOME_CATEGORIES or category in TRANSFER_CATEGORIES or category in SERVICE_CATEGORIES:
        return category
    return "pending"


def validate_manual_category_sign(amount: int, category: str | None) -> str | None:
    """Перевіряє, чи відповідає категорія знаку суми при ручному виборі.

    Використовується в POST /transactions/manual і PATCH /transactions/{id};
    категорію не підміняє. Від'ємна сума не може бути доходом чи отриманою
    позикою, додатна — витратою. Перекази дозволені для обох знаків.

    Args:
        amount: Сума в копійках.
        category: Обрана категорія.

    Returns:
        Текст помилки для відповіді 422 або None, якщо категорія допустима.
    """
    if category is None:
        return None
    if amount < 0 and category == LOAN_RECEIVED_CATEGORY:
        return (
            f"Від'ємна сума (відтік) не може мати категорію «{category}» — це надходження "
            "позичених грошей. Погашення позики — «Борги та кредити»; переказ на власний "
            "рахунок — «Переказ між власними рахунками»."
        )
    if amount < 0 and category in INCOME_CATEGORIES:
        return (
            f"Від'ємна сума (відтік) не може мати категорію доходу «{category}». "
            "Оберіть категорію витрат або переказу (Заощадження/Інвестиції)."
        )
    if guard_positive_amount_category(amount, category) == "pending":
        return (
            f"Додатна сума (надходження) не може мати категорію витрат «{category}». "
            "Якщо це повернення витрати (частка спільного рахунку) — "
            "POST /transactions/{id}/mark-reimbursement; якщо повернення позики — "
            "POST /transactions/{id}/repay-loan; інакше оберіть категорію доходу "
            "або переказу (Заощадження/Інвестиції)."
        )
    return None


def categorize_by_mcc(mcc: int) -> str | None:
    """Повертає сиру категорію за MCC-кодом або None."""
    return MCC_CATEGORIES.get(mcc)


def categorize_by_keyword(description: str) -> str | None:
    """Повертає сиру категорію за першим ключовим словом, що входить в опис, або None."""
    if not description:
        return None
    desc_lower = description.lower()
    for keyword, category in KEYWORD_CATEGORIES.items():
        if keyword in desc_lower:
            return category
    return None


def categorize_by_income_keyword(description: str) -> str | None:
    """Повертає підкатегорію доходу за ключовими словами доходу або None.

    Перевіряє лише INCOME_KEYWORD_CATEGORIES, тож результат завжди є категорією доходу.
    """
    if not description:
        return None
    desc_lower = description.lower()
    for keyword, category in INCOME_KEYWORD_CATEGORIES.items():
        if keyword in desc_lower:
            return category
    return None


def categorize_transaction(mcc: int, description: str, amount: int) -> tuple[str | None, str]:
    """Категоризує транзакцію правилами: спершу за MCC, потім за ключовими словами.

    Args:
        mcc: MCC-код; 4829 (перекази) пропускається.
        description: Опис транзакції.
        amount: Сума в копійках; додатна сума не отримує категорію витрат.

    Returns:
        Пара (канонічна категорія після CATEGORY_MERGE, метод), де метод — 'mcc',
        'keyword' або 'pending'. Для 'pending' категорія — None.
    """
    raw_category = None
    method = "pending"

    if mcc and mcc != 4829:
        raw_category = categorize_by_mcc(mcc)
        if raw_category:
            method = "mcc"

    if raw_category is None and description:
        raw_category = categorize_by_keyword(description)
        if raw_category:
            method = "keyword"

    if raw_category is None:
        return None, "pending"

    merged = CATEGORY_MERGE.get(raw_category, raw_category)
    if merged is None:
        # Занадто розмита категорія (наприклад, «Магазини»).
        return None, "pending"

    if guard_positive_amount_category(amount, merged) == "pending":
        return None, "pending"

    return merged, method
